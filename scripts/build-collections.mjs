// Generates the standalone /collections/ hub: public/collections/index.html,
// one card per tune-index page (see scripts/lib/tune-index-page.mjs), with tune
// counts read from each page's dataset (scripts/<slug>/tunes.json).
// Add a new tune-index page to COLLECTIONS below and re-run:
//   node scripts/build-collections.mjs
// Linked from the app's add-tune page ("Browse collections").
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { BASE_CSS, esc } from './lib/tune-index-page.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const base = 'https://tunebox.net/collections/';

const COLLECTIONS = [
  {
    group: 'Irish',
    items: [
      { slug: 'oneills-1001', name: "O'Neill's 1001", sub: "Francis O'Neill · The Dance Music of Ireland, 1907", blurb: 'The classic Chicago collection of jigs, reels, hornpipes and set dances.', own: true },
      { slug: 'ceol-rince-na-heireann', name: 'Ceol Rince na hÉireann 1–5', sub: 'Breandán Breathnach · 1963–1999', blurb: 'The standard reference for Irish dance music, with every Irish and English title.' },
      { slug: 'foinn-seisiun', name: 'Foinn Seisiún 1–3', sub: 'Comhaltas Ceoltóirí Éireann', blurb: 'The Comhaltas session-tune sets many Irish music classes learn from.' },
      { slug: 'irish-session-tunes', name: 'Irish Session Tunes', sub: 'Ossian · Green, Red, Blue & Orange books', blurb: 'Popular learner books of session sets, as listed on their companion CDs.' },
      { slug: '110-irelands-best-session-tunes', name: "110 Ireland's Best Session Tunes", sub: 'Waltons · volume 1', blurb: 'The best-known session reels, jigs and hornpipes, from the companion CDs.' },
    ],
  },
  {
    group: 'Scottish & Cape Breton',
    items: [
      { slug: 'kerrs-merry-melodies', name: "Kerr's Merry Melodies 1–4", sub: 'James S. Kerr · Glasgow, c. 1880s', blurb: 'Scotch and Irish reels, strathspeys, jigs and hornpipes for the violin.', own: true },
      { slug: 'skye-collection', name: 'The Skye Collection', sub: 'Keith Norman MacDonald · 1887', blurb: 'The best reels and strathspeys — a cornerstone of Cape Breton fiddling.', own: true },
      { slug: 'athole-collection', name: 'The Athole Collection', sub: 'James Stewart-Robertson · 1884', blurb: 'The dance music of Scotland: strathspeys, reels, jigs and more.', own: true },
    ],
  },
  {
    group: 'American & contra',
    items: [
      { slug: 'portland-collection', name: 'The Portland Collection 1–3', sub: 'Susan Songer · contra dance tunes', blurb: 'The contra dance tunebook series from Portland, Oregon.' },
      { slug: 'new-england-fiddlers-repertoire', name: "New England Fiddler's Repertoire", sub: 'Randy Miller & Jack Perron · 1983', blurb: 'The established tunes of New England contra dancing.' },
      { slug: 'ryans-mammoth-collection', name: "Ryan's Mammoth Collection", sub: 'William Bradbury Ryan · Boston, 1883', blurb: "The fiddler's bible, later sold as Cole's 1000 Fiddle Tunes.", own: true },
    ],
  },
];

const stats = (slug) => {
  const tunes = JSON.parse(readFileSync(join(root, 'scripts', slug, 'tunes.json'), 'utf8'));
  return { total: tunes.length, linked: tunes.filter((t) => t.url).length, playable: tunes.filter((t) => t.abc).length };
};
const all = COLLECTIONS.flatMap((g) => g.items.map((c) => Object.assign(c, stats(c.slug))));
const totalTunes = all.reduce((a, c) => a + c.total, 0).toLocaleString('en');

const card = (c) => `<a class="coll" href="/${c.slug}/">
  <span class="coll-name">${esc(c.name)}</span>
  <span class="coll-sub">${esc(c.sub)}</span>
  <span class="coll-blurb">${esc(c.blurb)}</span>
  <span class="coll-chips">
    <span class="chip chip-book">${c.total.toLocaleString('en')} tunes</span>
    <span class="chip">${c.own ? 'Book&rsquo;s own notation' : `Sheet music for ${c.playable.toLocaleString('en')}`}</span>
    <span class="chip">${c.linked.toLocaleString('en')} on thesession</span>
  </span>
</a>`;

const description = `Free searchable indexes of ${all.length} traditional tune collections — O'Neill's, Ceol Rince na hÉireann, Kerr's, the Skye and Athole collections, Portland, NEFR, Ryan's and more — ${totalTunes} tunes with sheet music, playback and links to thesession.org.`;

const html = `<!doctype html>
<!-- GENERATED by scripts/build-collections.mjs — do not edit by hand. -->
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="referrer" content="strict-origin-when-cross-origin">
<meta http-equiv="Content-Security-Policy" content="default-src 'self'; script-src 'self' https://gc.zgo.at; style-src 'self' 'unsafe-inline'; connect-src 'self' https://tunebox.goatcounter.com; img-src 'self' data: https://tunebox.goatcounter.com; font-src 'self' data:; object-src 'none'; base-uri 'self'; form-action 'self'">
<title>Traditional tune collections — searchable indexes of ${all.length} tunebooks</title>
<meta name="description" content="${esc(description)}">
<link rel="canonical" href="${base}">
<link rel="icon" type="image/svg+xml" href="/tunebook-logo.svg">
<meta property="og:type" content="website">
<meta property="og:site_name" content="TuneBox">
<meta property="og:url" content="${base}">
<meta property="og:title" content="Traditional tune collections — ${all.length} tunebooks, ${totalTunes} tunes">
<meta property="og:description" content="${esc(description)}">
<meta property="og:image" content="https://tunebox.net/og-image.png">
<meta name="twitter:card" content="summary">
<script type="application/ld+json">
${JSON.stringify({
  '@context': 'https://schema.org',
  '@type': 'CollectionPage',
  name: 'Traditional tune collections',
  url: base,
  description,
  isPartOf: { '@type': 'WebSite', name: 'TuneBox', url: 'https://tunebox.net/' },
  hasPart: all.map((c) => ({ '@type': 'CollectionPage', name: `${c.name} tune index`, url: `https://tunebox.net/${c.slug}/` })),
}, null, 2)}
</script>
<script data-goatcounter="https://tunebox.goatcounter.com/count" async src="https://gc.zgo.at/count.js"></script>
<style>
${BASE_CSS}
  .group h2 { margin:2rem 0 .75rem; font-size:.8rem; font-weight:600; text-transform:uppercase; letter-spacing:.05em; color:var(--gray-500); }
  .grid { display:grid; grid-template-columns:repeat(auto-fill, minmax(16rem, 1fr)); gap:.75rem; }
  .coll {
    display:flex; flex-direction:column; gap:.3rem; padding:1rem 1.1rem; text-decoration:none; color:inherit;
    background:#fff; border:1px solid var(--gray-200); border-radius:.75rem;
  }
  .coll:hover { border-color:var(--brand-600); }
  .coll:focus-visible { outline:2px solid var(--brand-600); outline-offset:1px; }
  .coll-name { font-weight:600; font-size:1.05rem; color:var(--gray-900); }
  .coll-sub { font-size:.8rem; color:var(--gray-500); }
  .coll-blurb { font-size:.88rem; color:var(--gray-600); flex:1; }
  .coll-chips { display:flex; flex-wrap:wrap; gap:.3rem; margin-top:.35rem; }
</style>
</head>
<body>
<header class="site">
  <div class="wrap">
    <span class="site-title">Tune collections</span>
    <a class="site-brand" href="https://tunebox.net/">hosted by <img src="/tunebook.svg" alt="TuneBox"></a>
  </div>
</header>

<div class="wrap">
  <section class="hero">
    <div class="hero-intro">
      <h1>Traditional tune <span class="accent">collections</span></h1>
      <p>Searchable indexes of ${all.length} tunebooks of traditional dance music &mdash; ${totalTunes} tunes in all.
      Each index lists every tune in the book, with sheet music and playback and links to
      <a href="https://thesession.org" target="_blank" rel="noopener">thesession.org</a>. For the public-domain books the
      notation is the book&rsquo;s own.</p>
    </div>
  </section>

${COLLECTIONS.map((g) => `  <section class="group">
    <h2>${esc(g.group)}</h2>
    <div class="grid">
${g.items.map(card).join('\n')}
    </div>
  </section>`).join('\n')}

  <section class="promo">
    <h2>Learning tunes from these books?</h2>
    <p><a href="https://tunebox.net/">TuneBox</a> is a free digital tunebook and practice planner for traditional
    musicians. Import tunes from thesession.org in a couple of taps, keep your repertoire organized per instrument,
    and let spaced repetition decide what to practice tonight.</p>
    <a class="cta" href="https://tunebox.net/">Open TuneBox &mdash; it&rsquo;s free</a>
  </section>

  <footer class="site">
    <p>${all.length} collections &middot; ${totalTunes} tunes</p>
    <p>Independent indexes, not affiliated with the publishers or with thesession.org.
    &middot; page by <a href="https://tunebox.net/">TuneBox</a>.</p>
  </footer>
</div>
</body>
</html>
`;

mkdirSync(join(root, 'public', 'collections'), { recursive: true });
writeFileSync(join(root, 'public', 'collections', 'index.html'), html);
console.log(`collections: wrote index.html (${all.length} collections, ${totalTunes} tunes)`);
